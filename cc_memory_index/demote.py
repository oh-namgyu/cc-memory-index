"""The demote command: set a memory's tier to 'indexed' so it is listed in L1 (DESIGN §3.2, §10).

Only the tier line changes (it is added when absent); every other byte of the file is kept.
"""

from __future__ import annotations

from typing import Sequence

from . import frontmatter
from .build import EXIT_OK, EXIT_PARSE, EXIT_USAGE, BuildResult, outcome, run_build, swept, writing
from .plan import Refusal, refuse_if_migrating
from .safeio import StoreDir
from .store import L0_NAME, Config, Source, load_config, load_source, skip_reason, valid_source_name

INDEXED = "indexed"


def _source(sd: StoreDir, cfg: Config, name: str) -> Source:
    """The memory file name, read and parsed; anything else is refused."""
    if not valid_source_name(name):
        raise Refusal(EXIT_USAGE, f"{name!r} is not a memory file name")
    if name.lower() in (L0_NAME.lower(), cfg.l1_name.lower()):
        raise Refusal(EXIT_USAGE, f"{name} is generated by cc-memory-index, not a memory file")
    if name not in sd.names():  # exact case: a case-insensitive match would rename the file
        raise Refusal(EXIT_USAGE, f"no memory file named {name} in {sd.path}")
    reason = skip_reason(sd, name, 0)
    src = None
    if reason is None:
        src, reason = load_source(sd, name)
    if src is None:
        raise Refusal(EXIT_USAGE, f"{name} cannot be demoted: {reason}")
    if not src.fm.ok:
        raise Refusal(EXIT_PARSE, f"{name}: frontmatter cannot be parsed ({src.fm.error}); set its tier by hand")
    return src


def set_indexed(sd: StoreDir, cfg: Config, name: str) -> bool:
    """Replace or add `tier: indexed`; the caller holds the lock. True when the file changed."""
    src = _source(sd, cfg, name)
    try:
        text = frontmatter.patch(src.text, add={}, replace={"tier": INDEXED})
    except frontmatter.PatchError as e:
        raise Refusal(EXIT_PARSE, f"{name}: the tier cannot be set safely ({e}); set it by hand") from e
    if text == src.text:
        return False
    sd.replace(name, text.encode("utf-8"), src.fp)
    return True


def demote_files(store_path: str, files: Sequence[str]) -> BuildResult:
    """Set tier: indexed in each file under the store lock, without rendering.

    stats['demoted'] lists the files changed; a failure stops at that file and keeps the
    earlier ones (DESIGN §7.2: no rollback).
    """
    res = BuildResult(EXIT_OK)
    changed: list[str] = []
    res.stats["demoted"] = changed
    with outcome(res), StoreDir(store_path) as sd:
        cfg = load_config(sd)
        with writing(sd, cfg.lock_timeout_s, res.stats):
            refuse_if_migrating(sd, EXIT_USAGE)
            for name in files:
                if set_indexed(sd, cfg, name):
                    changed.append(name)
    return res


def run_demote(store_path: str, file: str) -> BuildResult:
    """Demote one memory, then build; the result is the build's, plus stats['demoted'] and both sweeps."""
    demoted = demote_files(store_path, [file])
    if demoted.code != EXIT_OK:
        return demoted
    res = run_build(store_path, force=False)
    note = f"{file}: tier set to {INDEXED}" if demoted.stats["demoted"] else f"{file} already has tier {INDEXED}"
    res.messages.insert(0, note)
    res.stats["demoted"] = demoted.stats["demoted"]
    res.stats["temp_removed"] = swept(demoted, res)
    return res
